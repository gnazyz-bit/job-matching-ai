from __future__ import annotations
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from job_matching.data.resume_repository import ResumeRepository
from job_matching.ml.features import (
    FEATURES,
    create_features,
    parse_levels,
    safe_text,
)
from job_matching.ml.training import train_classifier
from job_matching.services.cover_letter_service import create_cover_letter
from job_matching.services.recommendation_service import matching_reasons, resume_advice


def run_pipeline(resume_path, vacancies_path, output_dir, chosen_rank=1):
    resume_object = ResumeRepository().load(str(resume_path))
    resume = resume_object.model_dump() if hasattr(resume_object, "model_dump") else resume_object.dict()
    vacancies = pd.read_csv(vacancies_path)
    required = {"title", "description"}
    if not required.issubset(vacancies.columns):
        raise ValueError("Missing vacancy columns: " + ", ".join(sorted(required - set(vacancies.columns))))
    vacancies = vacancies.loc[vacancies["title"].notna() & vacancies["title"].astype(str).str.strip().ne("")].reset_index(drop=True)
    if len(vacancies) < 20:
        raise ValueError("At least 20 vacancies are required")
    
    profiles_path = Path("data/samples/synthetic_resumes.json")

    with profiles_path.open("r", encoding="utf-8") as file:
        profiles = json.load(file)

    if not isinstance(profiles, list) or not profiles:
        raise ValueError("Synthetic resumes file must contain a non-empty list")

    features = create_features(profiles, vacancies)

    model, synthetic, metrics, train_count, test_count = train_classifier(
        features, len(profiles)
    )

    # Match the selected resume separately from the training profiles.
    candidates = create_features([resume], vacancies)
    
    candidates["model_score"] = model.predict_proba(candidates[FEATURES])[:, 1]
    # Disclose mismatches instead of letting an overly confident synthetic classifier hide them.
    seniorities = candidates["vacancy_id"].map(lambda i: parse_levels(vacancies.iloc[int(i)].get("seniority", "")))
    experience_factor = np.where(
        seniorities.str.contains("senior|lead|director|executive", regex=True),
        np.where(candidates["experience_fit"] < 0.38, 0.15, 1.0),
        np.where(candidates["experience_fit"] < 0.38, 0.65, 1.0),
    )
    candidates["match_score"] = candidates["model_score"] * experience_factor
    # Prevent generic shared titles (e.g. Logistics Analyst vs Data Analyst) from dominating.
    candidates = candidates.loc[candidates["role_overlap"] >= 0.67].copy()
    
    
    if candidates.empty:
        output = Path(output_dir)
        output.mkdir(parents=True, exist_ok=True)

        joblib.dump(model, output / "classifier.joblib")

        synthetic[
            ["profile_id", "vacancy_id", *FEATURES, "label"]
        ].to_csv(output / "training_pairs.csv", index=False)

        candidates.to_csv(output / "ranked_vacancies.csv", index=False)

        report = "\n".join([
            "JOB MATCHING AI - HIMALAYAS",
            "",
            "TRAINING NOTE: Labels were generated by rules, not human annotation.",
            "",
            "RECOMMENDED VACANCIES:",
            "No sufficiently matching vacancies were found in the current dataset.",
            "",
            "RESUME SUGGESTIONS:",
            "No vacancy-specific suggestions are available because no matching vacancy was found.",
            "",
            "COVER LETTER:",
            "Not generated because no suitable vacancy was selected.",
            "",
            "EVALUATION ON HELD-OUT RULE-LABELED PAIRS:",
            metrics,
            "This evaluation does not measure real-world hiring accuracy.",
        ]) + "\n"

        (output / "recommendations_and_letter.txt").write_text(
            report, encoding="utf-8"
        )

        return {
            "report": report,
            "training_count": train_count,
            "test_count": test_count,
            "ranked_count": 0,
        }

    candidates = candidates.sort_values("match_score", ascending=False).reset_index(drop=True)
    columns = [c for c in ("title", "company", "url", "seniority", "salary_from", "salary_to", "salary_currency", "salary_period") if c in vacancies.columns]
    ranked = candidates.merge(vacancies[columns], left_on="vacancy_id", right_index=True, how="left")
    if not 1 <= chosen_rank <= min(5, len(ranked)):
        raise ValueError("Chosen rank must refer to one of the first five recommendations")
    selected = ranked.iloc[chosen_rank - 1]
    vacancy = vacancies.iloc[int(selected["vacancy_id"])]
    lines = ["JOB MATCHING AI — HIMALAYAS", "", "TRAINING NOTE: labels were generated by explicit rules, not human annotation.",
             "Model scores are not verified probabilities of hiring suitability.", "", "RECOMMENDED VACANCIES:"]
    for index, row in ranked.head(5).iterrows():
        lines.append(f"{index + 1}. {row['title']} — {safe_text(row.get('company'))}")
        lines.append(f"   Model score: {row['match_score']:.3f} | Why: {'; '.join(matching_reasons(row))}")
        lines.append(f"   URL: {safe_text(row.get('url'))}")
    lines += ["", f"RESUME SUGGESTIONS (vacancy #{chosen_rank}):"]
    lines += ["- " + suggestion for suggestion in resume_advice(selected, resume)]
    lines += ["", f"COVER LETTER (vacancy #{chosen_rank}):", create_cover_letter(resume, vacancy, selected["matched_skills"]),
              "", "EVALUATION ON HELD-OUT RULE-LABELED PAIRS:", metrics,
              "This evaluation does not measure real-world hiring accuracy."]
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, output / "classifier.joblib")
    synthetic[["profile_id", "vacancy_id", *FEATURES, "label"]].to_csv(output / "training_pairs.csv", index=False)
    ranked.to_csv(output / "ranked_vacancies.csv", index=False)
    report = "\n".join(lines) + "\n"
    (output / "recommendations_and_letter.txt").write_text(report, encoding="utf-8")
    return {"report": report, "training_count": train_count, "test_count": test_count, "ranked_count": len(ranked)}
